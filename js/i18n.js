  function t(key, vars) {
    let s = STR[lang][key];
    if (s === undefined) s = STR.fr[key];
    if (s === undefined) return key;
    if (typeof s === "string" && vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }

  function setLang(l) {
    if (!SUPPORTED.includes(l) || l === lang) return;
    try { localStorage.setItem(STORE, l); } catch (e) {}
    const url = new URL(location.href);
    if (url.searchParams.has("lang")) {
      url.searchParams.delete("lang");
      location.replace(url.toString());
    } else {
      location.reload();
    }
  }

  return { lang, t, setLang, SUPPORTED };
